int height(int scale) { return 7 * scale; }

// 6px advance per glyph (5 columns + 1px right gap) matches the draw loop.
int width(const std::string& s, int scale) { return (int)(s.size() * 6) * scale; }

static void blitGlyph(SDL_Renderer* r, unsigned char c, int x, int y, int scale,
                      Uint8 red, Uint8 green, Uint8 blue) {
  unsigned char uc = c & 0x7F;
  if (uc < 32 || uc > 126) return;
  const uint8_t* g = GLYPHS[uc - 32];
  SDL_SetRenderDrawColor(r, red, green, blue, 255);
  SDL_Rect rc{};
  for (int row = 0; row < 7; ++row) {
    for (int col = 0; col < 5; ++col) {
      // Bit 4 of the row byte is the leftmost of the 5 columns.
      if (g[row] & (0x10 >> col)) {
        rc.x = x + col * scale;
        rc.y = y + row * scale;
        rc.w = scale;
        rc.h = scale;
        SDL_RenderFillRect(r, &rc);
      }
    }
  }
}

void draw(SDL_Renderer* r, const std::string& s, int x, int y,
          Uint8 r8, Uint8 g8, Uint8 b8, int scale, int maxWidth) {
  // Two-pass render: stamp the string once per 8-neighbour offset in black,
  // then draw the fill on top. The dark halo keeps text readable on the
  // busy photo backgrounds without a solid backdrop.
  for (int dx = -1; dx <= 1; ++dx) {
    for (int dy = -1; dy <= 1; ++dy) {
      if (!dx && !dy) continue;
      int cx = x, cy = y;
      for (size_t i = 0; i < s.size(); ++i) {
        if (s[i] == ' ') { cx += 6 * scale; continue; }
        blitGlyph(r, (unsigned char)s[i], cx + dx, cy + dy, scale, 0, 0, 0);
        cx += 6 * scale;
        if (maxWidth && cx - x >= maxWidth) break;
      }
    }
  }
  int cx = x, cy = y;
  for (size_t i = 0; i < s.size(); ++i) {
    if (s[i] == ' ') { cx += 6 * scale; continue; }
    blitGlyph(r, (unsigned char)s[i], cx, cy, scale, r8, g8, b8);
    cx += 6 * scale;
    if (maxWidth && cx - x >= maxWidth) break;
  }
}

